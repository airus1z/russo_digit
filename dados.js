const Dicionarios = {
    // Transliteração científica (ISO 9) com regras para 'E' inicial
    transliterarCirilico: function(texto) {
        const mapaBase = {
            'А': 'A', 'а': 'a',
            'Б': 'B', 'б': 'b',
            'В': 'V', 'в': 'v',
            'Г': 'G', 'г': 'g',
            'Д': 'D', 'д': 'd',
            'Ё': 'Yo', 'ё': 'yo',
            'Ж': 'Zh', 'ж': 'zh',
            'З': 'Z', 'з': 'z',
            'И': 'I', 'и': 'i',
            'Й': 'Y', 'й': 'y',
            'К': 'K', 'к': 'k',
            'Л': 'L', 'л': 'l',
            'М': 'M', 'м': 'm',
            'Н': 'N', 'н': 'n',
            'О': 'O', 'о': 'o',
            'П': 'P', 'п': 'p',
            'Р': 'R', 'р': 'r',
            'С': 'S', 'с': 's',
            'Т': 'T', 'т': 't',
            'У': 'U', 'у': 'u',
            'Ф': 'F', 'ф': 'f',
            'Х': 'Kh', 'х': 'kh',
            'Ц': 'Ts', 'ц': 'ts',
            'Ч': 'Ch', 'ч': 'ch',
            'Ш': 'Sh', 'ш': 'sh',
            'Щ': 'Shch', 'щ': 'shch',
            'Ъ': '', 'ъ': '',
            'Ы': 'Y', 'ы': 'y',
            'Ь': '', 'ь': '',
            'Э': 'E', 'э': 'e',
            'Ю': 'Yu', 'ю': 'yu',
            'Я': 'Ya', 'я': 'ya'
        };

        // Caracteres que são vogais ou sinais suaves/difíceis que afetam a regra do E
        const vogais = 'АаЕеЁёИиОоУуЫыЭэЮюЯяЬьЪъ';

        let resultado = "";
        for (let i = 0; i < texto.length; i++) {
            const char = texto[i];
            const anterior = i > 0 ? texto[i-1] : " ";
            // Início de palavra: começo do texto ou depois de espaço/hífen/pontuação
            const ehInicio = i === 0 || /[^А-Яа-яЁё]/.test(anterior);
            const anteriorVogal = vogais.includes(anterior);

            // Regra especial para 'Е' e 'е'
            if (char === 'Е') {
                // Se for início ou após vogal/sinal, translitera como "Ye"
                if (ehInicio || anteriorVogal) {
                    resultado += "Ye";
                } else {
                    resultado += "E";
                }
            } else if (char === 'е') {
                if (ehInicio || anteriorVogal) {
                    resultado += "ye";
                } else {
                    resultado += "e";
                }
            } else if (mapaBase[char] !== undefined) {
                resultado += mapaBase[char];
            } else {
                resultado += char;
            }
        }
        return resultado;
    }
};

